#!/usr/bin/env bash
# ════════════════════════════════════════════════════════════════════
# Генерирует engine-install/engine-files.txt — список файлов движка
# для резервного скачивания ПО ОДНОМУ.
#
# Зачем: установщики движка сначала качают tarball всего репозитория
# (github.com → codeload.github.com). На части сетей этот трафик
# перехватывается провайдером/антивирусом (curl: «SEC_E_WRONG_PRINCIPAL»,
# PowerShell: «доверительные отношения SSL/TLS»), а вот
# raw.githubusercontent.com остаётся доступен — с него же скачивается
# сам установщик. Тогда установщик берёт этот список и качает каждый
# файл отдельно.
#
# Формат: путь файла в репозитории + строка-комментарий «# size <путь> <байт>»
# с ожидаемым размером. Установщик сверяет размер скачанного файла: пустая
# заглушка перехватчика (HTTP 200 без тела) отсеивается по несовпадению
# размера, а легитимно пустые файлы (как пустые __init__.py в src/) с
# ожидаемым размером 0 скачиваются успешно. Без этой строки установщик
# браковал пустые файлы как «перехват» — и резервный способ никогда не
# доходил до конца (см. Task 61).
#
# Когда пересоздавать: после любого изменения СОСТАВА или СОДЕРЖИМОГО
# файлов (добавили/удалили/перенесли/изменили файл в src/, engine_server.py,
# requirements-engine.txt). CI (windows-e2e) сверяет свежесть, включая
# размеры.
#
# Запуск из корня репозитория:  bash engine-install/gen-files-manifest.sh
# ════════════════════════════════════════════════════════════════════
set -e
cd "$(dirname "$0")/.."
{
    echo "# Файлы движка для резервного скачивания по одному (raw-fallback)."
    echo "# Пересоздавать после изменения состава или содержимого файлов:"
    echo "#   bash engine-install/gen-files-manifest.sh"
    git ls-files engine_server.py engine-install/requirements-engine.txt src/ | while IFS= read -r f; do
        printf '%s\n' "$f"
        # Размер берём из git-блоба, а не с диска: на чекаутах с CRLF
        # (например, Windows-раннеры CI) wc -c насчитал бы другие байты,
        # а размер блоба всегда соответствует тому, что отдаёт raw.
        sha=$(git ls-files -s -- "$f" | awk '{print $2}')
        printf '# size %s %s\n' "$f" "$(git cat-file -s "$sha")"
    done
} > engine-install/engine-files.txt
echo "OK: engine-install/engine-files.txt — $(grep -vc '^#' engine-install/engine-files.txt) файлов"
